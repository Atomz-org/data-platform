"""Generate staging models from ontology annotations.

Staging contract, enforced here rather than by convention:
  * strictly 1:1 with a raw table — same grain, one model per resource
  * cleaning happens HERE and nowhere else downstream
  * renaming and casting
  * deduplication to the declared key
  * NO joins, NO aggregation, NO filtering that changes the grain

Because cleaning is driven by the column's declared role, every project cleans
the same way and a new company inherits the rules for free.
"""

from __future__ import annotations

from pathlib import Path

from pf.ontology.annotate import Annotation, load_annotations
from pf.ontology.model import load_ontology

# role -> (column-name suffix convention, whether it needs a dbt test)
RENAME_HINTS = {
    "natural_key": "_id",
    "event_time": "_at",
    "valid_from": "_from",
    "valid_to": "_to",
    "money_amount": "_amount",
    "currency_code": "_code",
    "geo_country": "_code",
}

HEADER = """\
{{# GENERATED by `pf gen-staging` from contracts/annotations.yaml. #}}
{{#
  Staging contract: 1:1 with `{source}.{table}` — one row in, one row out.
  Cleaning is applied here via role-driven macros and is NOT repeated downstream.
  Do not add joins, aggregation, or grain-changing filters to this model.
  Concept: {concept} · Grain: {grain}
#}}
"""


def _target_name(col: str, role: str, rename: dict[str, str]) -> str:
    """Warehouse column name: an explicit rename wins, else a role-driven default."""
    if col in rename:
        return rename[col]
    if role in ("natural_key", "surrogate_key") and not col.endswith("_id"):
        return f"{col}_id"
    return col


def render_staging_sql(ann: Annotation, prefix: str = "stg") -> str:
    """Render one staging model. Deterministic, so regeneration is a no-op diff."""
    load_ontology()
    src, table = ann.source or "raw", ann.resource
    lines = [HEADER.format(source=src, table=table, concept=ann.concept,
                           grain=ann.grain or "undeclared")]
    lines.append("with renamed as (\n    select")

    key_col: str | None = None
    select_parts: list[str] = []
    seen: set[str] = set()

    for col, role in ann.roles.items():
        seen.add(col)
        if role in ("natural_key", "surrogate_key"):
            key_col = col
        target = _target_name(col, role, ann.rename)
        # Every column is aliased. An unaliased macro call names the column after
        # the expression, which silently breaks every downstream model.
        select_parts.append(f"        {{{{ pf_clean('{col}', '{role}') }}}} as {target},")

    for col, target_class in ann.links.items():
        if col in seen:
            continue
        seen.add(col)
        target = _target_name(col, "foreign_key", ann.rename)
        select_parts.append(
            f"        {{{{ pf_clean('{col}', 'foreign_key') }}}} as {target},"
            f"  -- → {target_class}")

    # dlt bookkeeping: keep the load id, it is the dedupe ordering column
    select_parts.append("        _dlt_load_id,")
    if select_parts:
        select_parts[-1] = select_parts[-1].rstrip(",")

    lines.extend(select_parts)
    lines.append(f"    from {{{{ source('{src}', '{table}') }}}}")
    lines.append(")\n")
    lines.append("select * exclude (_dlt_load_id)")
    lines.append("from renamed")
    if key_col:
        target_key = _target_name(key_col, ann.roles[key_col], ann.rename)
        lines.append(f"where {target_key} is not null")
        lines.append(f"{{{{ pf_dedupe('{target_key}') }}}}")
    return "\n".join(lines) + "\n"


def render_staging_yml(anns: list[Annotation], prefix: str = "stg") -> str:
    """Schema yml with tests generated from the same roles."""
    onto = load_ontology()
    pii = onto.pii_roles()
    out = ["version: 2", "", "models:"]
    for ann in anns:
        src = ann.source or "raw"
        name = f"{prefix}_{src}__{ann.resource}"
        out.append(f"  - name: {name}")
        out.append("    description: >")
        out.append(f"      {ann.description or ann.resource}. Cleaned 1:1 from "
                   f"`{src}.{ann.resource}`; grain: {ann.grain or 'undeclared'}.")
        out.append("    meta:")
        out.append(f"      concept: {ann.concept}")
        out.append(f"      grain: {ann.grain or 'undeclared'}")
        out.append("      layer: staging")
        out.append("    columns:")
        for col, role in ann.roles.items():
            target = _target_name(col, role, ann.rename)
            out.append(f"      - name: {target}")
            out.append(f"        meta: {{role: {role}"
                       + (", pii: true}" if role in pii else "}"))
            tests: list[str] = []
            if role in ("natural_key", "surrogate_key"):
                tests = ["unique", "not_null"]
            elif role in ("money_amount", "event_time"):
                tests = ["not_null"]
            if tests:
                out.append(f"        data_tests: [{', '.join(tests)}]")
        for col, target_class in ann.links.items():
            if col in ann.roles:
                continue
            out.append(f"      - name: {_target_name(col, 'foreign_key', ann.rename)}")
            out.append(f"        description: Foreign key to {target_class}.")
            out.append(f"        meta: {{role: foreign_key, links_to: {target_class}}}")
        out.append("")
    return "\n".join(out)


def generate(project_dir: str | Path, prefix: str = "stg",
             overwrite: bool = False) -> list[Path]:
    """Write staging models + schema yml for every annotated resource."""
    root = Path(project_dir)
    anns = load_annotations(root / "contracts" / "annotations.yaml")
    if not anns:
        raise FileNotFoundError(
            "contracts/annotations.yaml is missing or empty — run `pf seed` first")

    written: list[Path] = []
    by_source: dict[str, list[Annotation]] = {}
    for ann in anns:
        by_source.setdefault(ann.source or "raw", []).append(ann)

    for src, group in by_source.items():
        sdir = root / "transform" / "models" / "staging" / src
        sdir.mkdir(parents=True, exist_ok=True)

        sources_yml = sdir / f"_{src}__sources.yml"
        if overwrite or not sources_yml.exists():
            body = ["version: 2", "", "sources:", f"  - name: {src}",
                    f"    schema: {src}",
                    "    description: Raw data landed by dlt. Schema owned by the source.",
                    "    tables:"]
            body += [f"      - name: {a.resource}" for a in group]
            sources_yml.write_text("\n".join(body) + "\n", encoding="utf-8")
            written.append(sources_yml)

        for ann in group:
            f = sdir / f"{prefix}_{src}__{ann.resource}.sql"
            if overwrite or not f.exists():
                f.write_text(render_staging_sql(ann, prefix), encoding="utf-8")
                written.append(f)

        schema = sdir / f"_{src}__models.yml"
        if overwrite or not schema.exists():
            schema.write_text(render_staging_yml(group, prefix), encoding="utf-8")
            written.append(schema)

    return written

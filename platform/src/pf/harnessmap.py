"""The harness map: what wraps an agent in one scope of this repository.

Three scopes, three `HARNESS.md`:

    groups/<g>/HARNESS.md                          what every sister inherits
    groups/<g>/projects/<p>/HARNESS.md             one entity, as an agent meets it
    groups/<g>/projects/<p>/reporting/HARNESS.md   the Evidence report inside it

Not `pf.harness`, which is the per-*tool* layer: it renders the Codex, Cursor,
Gemini, VS Code and OpenCode configs from `.mcp.json` and keeps the scorecard
in `docs/HARNESSES.md` — which harness gets what, repository-wide. This is the
per-*scope* layer: which of that reaches one group, one project and one
report, and everything scoped to it that a repository-wide table cannot say —
this project's settings and hooks, the gate's verdicts on its paths, its
workflow, its loops, its tools. The project map carries the scorecard's rows,
computed for the project, so the two agree by construction.

"Harness" here is everything a person or an agent is wrapped in while working
in that scope, in the order they meet it: what a session is handed on turn one,
what it may read and write, what runs around every edit, what a commit must
pass, what every pull request runs, what runs on a schedule, and what is
recorded. None of it is asserted. Every line is read from the file that
enforces it — `.claude/settings.json`, `gate.yaml` and the capability rules
merged over it, the hook scripts, the project's workflow, the group's
`loops.yaml`, `tools.yaml`, `air.yaml` and `notify.yaml` — or from the
registry that declares it. The gate verdicts are not read from `gate.yaml` at
all: they are computed by calling the function the PreToolUse hook calls, on
representative paths, so the map says what the hook would do rather than what
the policy file appears to say. Those two differ, and the difference is
reported as a gap rather than smoothed over.

Two rules keep it honest across machines. Nothing machine-local goes in: not
whether a tool is installed, which Node is on the path, whether the commit
hook is linked or how fresh the graph is — those are the SessionStart hook's
job, on turn one, on that machine. And nothing that moves without the project
moving: no date, no commit, no count of an ignored file. The files are
compared byte for byte, and anything that differs between a laptop and a CI
runner turns `pf harness check` into a coin toss.

Generated on the same terms as `kg/architecture.md`, and beside it in every
way: written by `pf harness <group> <project>` and by every `pf bootstrap`,
denied to hand edits by the gate, carried by git so a pull request that
enables a tool or silences a loop shows what that did to the harness, in the
diff, next to the change.
"""


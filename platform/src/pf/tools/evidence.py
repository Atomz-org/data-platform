"""Evidence — the reporting layer, as a Tool.

Evidence was wired in before the `Tool` seam existed, and it is the example the
seam's docstring gives of why the seam was needed: seven places touched to add
one tool. This module folds those seven into one declaration. Nothing about
what Evidence *does* changes — `pf.projections.evidence` still compiles every
page from a metric, `report_audit` still scores the result — only where the
wiring lives.

What the declaration carries:

  * **capability** — the files, settings and gate rules `reporting/` needs.
    Moved here from `pf.capabilities` verbatim; same name, so `pf new-project
    --with evidence` and every existing `tools.yaml` keep working.
  * **bootstrap** — regenerate the project from the semantic layer. The same
    code the `reporting` bootstrap step ran; that step now defers to this.
  * **dagster** — a `reporting` asset downstream of the marts, with the audit
    score as metadata, so a metric change shows its page going stale.
  * **surface** — the dev server, for `pf ui` → Review to embed.
  * **health** — Node 20. Evidence 40 does not build on Node 24, and "installed"
    was never the question; "builds" is.
  * **loops** — `dashboard-coverage`, contributed here rather than listed in
    the registry. A loop about the reporting layer belongs to the reporting
    tool, and disappears with it.
"""

from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path
from typing import Any

from pf.capabilities import Capability
from pf.tools.spec import DbtBinding, Requirement, Surface, Tool, ToolContext, ToolContribution

README = """\
# Reporting — Evidence BI

BI-as-code for **{{group}}/{{project}}**. Generated by `pf report build`, never
hand-maintained.

    dbt marts -> MetricFlow metrics -> MDL -> queries/metrics/*.sql -> pages/*.md

## The one rule

**Pages never restate business logic.** Every number traces to a metric compiled
into `queries/metrics/`. If a dashboard needs a figure that does not exist, the
fix is a metric definition in `transform/models/semantic/`, then `pf report build`
— not SQL in a page. Two pages filtering differently is how one company ends up
with two revenues.

## Ratio metrics

Ratio queries carry their numerator and denominator so a page re-divides at its
own grain: `sum(num) / sum(den)`. **Never `avg(ratio)`** — it is wrong at every
grain except the one it was computed at, and it is the most common BI bug there is.

## Commands

```bash
pf report build {{group}} {{project}}    # regenerate from the semantic layer
pf report audit {{group}} {{project}}    # mechanical quality score
pf ask {{group}} {{project}} "revenue by month"   # the same metrics, as a question
cd reporting && npm install && npm run sources && npm run dev
```

### Node version

Use **Node 20** (`.nvmrc` is committed). Evidence 40 does not build on Node 24 /
npm 11 — verified by building a pristine `evidence-dev/template`, which fails the
same way, so this is Evidence's supported-runtime boundary rather than anything
about this project. `npm run sources` and `npm run dev` work on newer Node;
`npm run build` needs 20. `pf tool doctor` checks.

## What is generated vs yours

| Generated — do not edit | Yours |
|---|---|
| `queries/metrics/*.sql` | extra pages you write by hand |
| `pages/index.md`, `pages/metrics/*.md` | `components/` |
| `sources/*/`, `evidence.config.yaml` | narrative text in generated pages* |

*Regenerating overwrites generated pages. Put durable narrative in a page you
own, or in the metric `description` so it survives.
"""


def _count(base: Path, globs: tuple[str, ...]) -> tuple[int, str]:
    """How many paths match, and the one to print.

    Glob order is honoured for the printed path and ignored for the count: the
    first glob is the feature's most descriptive location (`mdl/mdl.json`, not
    the `mdl/connection.json` that sorts before it), while the count has to be
    de-duplicated across globs that overlap.
    """
    seen: set[Path] = set()
    where = ""
    for g in globs:
        hits = sorted(base.glob(g), key=str)
        if hits and not where:
            where = str(hits[0].relative_to(base))
        seen.update(hits)
    return len(seen), where


def _graph_counts(pdir: Path) -> tuple[dict[str, int], int]:
    """Node counts by kind, and how many columns carry PII.

    Absent graph is a normal answer, not an error: a project is scaffolded
    before it is built, and this runs at scaffold time.
    """
    gp = pdir / "kg" / "graph.duckdb"
    if not gp.exists():
        return {}, 0
    try:
        from pf.kg.store import open_graph

        with open_graph(gp, read_only=True) as g:
            counts = dict(g.counts())
            pii = sum(1 for c in g.nodes("Column") if c.props.get("pii"))
        return counts, pii
    except Exception:  # noqa: BLE001 — a locked or half-built graph is not fatal
        return {}, 0


#: Lineage edges only. `has_column` and the semantic edges are true and would
#: turn a five-step example into a forty-step one.
_FLOW = ("feeds", "measures")


def _chain(pdir: Path, limit: int = 6) -> Chain:
    """One real path through the project, chosen as the most consequential.

    Preference runs downstream-first — an exposure is what somebody actually
    reads, so the chain that ends at one is the chain worth showing. Falling
    back through metric, mart and table means an empty project still gets an
    honest answer rather than a diagram of nothing.
    """
    gp = pdir / "kg" / "graph.duckdb"
    if not gp.exists():
        return Chain(note="no graph yet — run `pf seed`, then `pf kg build`")
    try:
        from pf.kg.store import open_graph

        with open_graph(gp, read_only=True) as g:
            target = None
            for kind in ("Exposure", "Metric", "Model", "Table"):
                pool = sorted(g.nodes(kind), key=lambda n: n.name)
                if kind == "Model":
                    pool = [m for m in pool if m.layer == "marts"] or pool
                if pool:
                    target = pool[0]
                    break
            if target is None:
                return Chain(note="the graph holds no tables yet — run `pf seed`")

            steps = [(target.kind, target.name)]
            seen, cur, more = {target.id}, target, False
            while True:
                parents = sorted(
                    (e for e in g.in_edges(cur.id)
                     if e.kind in _FLOW and e.src not in seen),
                    key=lambda e: e.src)
                if not parents:
                    break
                if len(steps) >= limit:
                    more = True
                    break
                nxt = g.node(parents[0].src)
                if nxt is None:
                    break
                seen.add(nxt.id)
                steps.append((nxt.kind, nxt.name))
                cur = nxt
            steps.reverse()
            if len(steps) == 1:
                return Chain(steps=steps,
                             note="nothing upstream — this node has no lineage yet")
            return Chain(steps=steps, truncated=more)
    except Exception as exc:  # noqa: BLE001 — the map must render without a graph
        return Chain(note=f"graph unreadable ({type(exc).__name__})")


def _warehouse(pdir: Path) -> str:
    """What `prod` actually points at, which is not always what it claims to."""
    p = pdir / "transform" / "profiles.yml"
    if not p.exists():
        return ""
    try:
        from pf.scaffold.generator import target_type

        return target_type(p.read_text(), "prod") or ""
    except Exception:  # noqa: BLE001
        return ""


def _tools(root: Path, group: str, project: str) -> list[str]:
    try:
        from pf.tools import enabled_names

        return sorted(enabled_names(root, group, project))
    except Exception:  # noqa: BLE001 — a broken tool registry must not stop the map
        return []


def _capabilities(root: Path, pdir: Path, group: str, project: str) -> list[str]:
    """Which capabilities this project actually has, judged by their own files.

    Asked rather than assumed: `defaults()` says what a *new* project would get,
    which is a different question from what this one has. A project scaffolded
    before a capability became a default has none of its files, and reporting it
    as enabled would be the map agreeing with the registry instead of with the
    project.

    Most capabilities do not earn a row in the coverage table — nine of them
    write one documentation page each — so this line is where they are named.
    """
    try:
        from pf.capabilities import CAPABILITIES, render

        ctx = {"group": group, "project": project,
               "module": project.replace("-", "_")}
        out = []
        for name, cap in sorted(CAPABILITIES.items()):
            targets = [(root if rel.startswith(".github/") else pdir) / rel
                       for rel in (render(r, ctx) for r in cap.files)]
            if targets and all(t.exists() for t in targets):
                out.append(name)
        return out
    except Exception:  # noqa: BLE001
        return []


def _unmapped(pdir: Path, registry: tuple[Feature, ...]) -> list[str]:
    """Top-level entries no feature claims.

    Top level only, and that is the point rather than a limitation: a platform
    feature earns a directory. `catalog/`, `evals/` and `mdl/` each arrived that
    way, and each would have appeared here on the day it was added.

    The registry is passed in rather than recomputed so this answers the same
    question the rest of the map does. Asking a second time would let a tool
    registered between the two calls produce a document that claims a directory
    its own unmapped list still reports.
    """
    claimed = {s for f in registry for s in f.segments}
    out = []
    for p in sorted(pdir.iterdir()):
        if p.name in IGNORED or p.name in claimed:
            continue
        out.append(p.name + ("/" if p.is_dir() else ""))
    return out


def gather(root: str | Path, group: str, project: str) -> Arch:
    """Everything the map needs, read only from this project."""
    root = Path(root)
    pdir = root / "groups" / group / "projects" / project
    counts, pii = _graph_counts(pdir)

    a = Arch(group=group, project=project, pdir=pdir, root=root,
             is_rollup=project.endswith("-rollup"),
             warehouse=_warehouse(pdir),
             module=project.replace("-", "_"),
             counts=counts, pii=pii,
             tools=_tools(root, group, project),
             caps=_capabilities(root, pdir, group, project),
             chain=_chain(pdir))

    if a.is_rollup:
        # Names only, from the group's own directory listing — the same thing
        # the group card publishes. No sister file is opened here or anywhere.
        sisters_dir = root / "groups" / group / "projects"
        if sisters_dir.exists():
            a.sisters = sorted(p.name for p in sisters_dir.iterdir()
                               if p.is_dir() and p.name != project
                               and not p.name.startswith("."))

    registry = features()
    for f in registry:
        n, where = _count(pdir, f.paths) if f.paths else (0, "")
        if f.repo_paths:
            rn, rwhere = _count(root, tuple(g.format(project=project, group=group)
                                            for g in f.repo_paths))
            n, where = n + rn, where or rwhere
        # A graph, when there is one, is the authority — including when its
        # answer is zero. Falling back to the file count on a missing *kind*
        # rather than a missing *graph* reported "raw tables: 1" for a roll-up
        # whose graph holds no tables at all, because one `data/*.duckdb` file
        # existed. The file count is only ever a stand-in for a project that has
        # not been built yet.
        if f.count_kind and counts:
            n = counts.get(f.count_kind, 0)
        if f.self_reporting:
            n = 1
        a.found.append(Presence(f, n, where or (f.paths or f.repo_paths or ("",))[0]))

    a.unmapped = _unmapped(pdir, registry) if pdir.exists() else []
    return a



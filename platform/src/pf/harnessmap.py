# ------------------------------------------------------------------ paths ---
def group_path(root: str | Path, group: str) -> Path:
    return Path(root) / "groups" / group / FILE


def project_path(root: str | Path, group: str, project: str) -> Path:
    return Path(root) / "groups" / group / "projects" / project / FILE


def report_path(root: str | Path, group: str, project: str) -> Path:
    return Path(root) / "groups" / group / "projects" / project / "reporting" / FILE


@dataclass(frozen=True)
class Scope:
    """One HARNESS.md: where it goes and how it is made."""

    kind: str  # group | project | report
    group: str
    project: str = ""

    @property
    def label(self) -> str:
        return (
            self.group
            if not self.project
            else f"{self.group}/{self.project}" + ("/reporting" if self.kind == "report" else "")
        )

    def path(self, root: str | Path) -> Path:
        if self.kind == "group":
            return group_path(root, self.group)
        if self.kind == "report":
            return report_path(root, self.group, self.project)
        return project_path(root, self.group, self.project)

    def render(self, root: str | Path) -> str:
        if self.kind == "group":
            return render_group(gather_group(root, self.group))
        if self.kind == "report":
            return render_report(gather_report(root, self.group, self.project))
        return render_project(gather_project(root, self.group, self.project))



DEFAULT_PORT = 3000
NODE_MAJOR = 20


# ---------------------------------------------------------------- helpers --
def reporting_dir(project_dir: Path) -> Path:
    return project_dir / "reporting"


def has_reporting(project_dir: Path) -> bool:
    return reporting_dir(project_dir).exists()


def node_version() -> tuple[int, ...] | None:
    node = shutil.which("node")
    if not node:
        return None
    try:
        out = subprocess.run([node, "--version"], capture_output=True, text=True,
                             timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    m = re.match(r"v?(\d+)\.(\d+)\.(\d+)", out)
    return tuple(int(x) for x in m.groups()) if m else None


def health() -> dict[str, Any]:
    """Builds, not merely installed. Node 20 is Evidence 40's runtime boundary."""
    v = node_version()
    if v is None:
        return {"ok": False, "detail": "node not found — install Node 20 (`.nvmrc`)"}
    if v[0] != NODE_MAJOR:
        return {"ok": False,
                "detail": f"node {'.'.join(map(str, v))} — Evidence 40 builds on Node "
                          f"{NODE_MAJOR} only (`nvm use`)"}
    return {"ok": True, "detail": f"node {'.'.join(map(str, v))}"}


# -------------------------------------------------------------- bootstrap --
def bootstrap_project(root: Path, group: str, project: str,
                      project_dir: Path, config: dict[str, Any]) -> Any:
    """Regenerate the reporting layer. Skipped where it was never opted into."""
    from pf.scaffold.bootstrap import StepResult

    if not has_reporting(project_dir):
        return StepResult("evidence", "skipped", "no reporting/ (`pf tool enable evidence`)")
    from pf.projections.evidence import build

    r = build(project_dir, group, project)
    detail = f"{r['metrics']} metric(s), {r['pages']} page(s)"
    if not r["metrics"]:
        detail += " · no metrics in the semantic layer yet"
    return StepResult("evidence", "ok", detail)


# ---------------------------------------------------------------- dagster --
def dagster_assets(ctx: ToolContext) -> ToolContribution:
    """The reporting layer as an asset downstream of the marts it renders."""
    from dagster import AssetKey, MetadataValue, asset

    project_dir = Path(ctx.project_dir)
    if not has_reporting(project_dir):
        return ToolContribution()
    from pf.projections.evidence import collect_metrics

    prefix = ctx.project.replace("-", "_")
    models = sorted({m.model for m in collect_metrics(project_dir) if m.model})
    deps = [AssetKey([prefix, m]) for m in models]

    @asset(
        name="reporting",
        key_prefix=[prefix],
        group_name="reporting",
        deps=deps,
        description="Evidence pages compiled from the semantic layer; audited on build.",
        compute_kind="evidence",
        metadata={"dagster/kind": "evidence", "tool": "evidence"},
    )
    def _reporting(context) -> None:  # noqa: ANN001 — see dagster_runtime note
        from pf.projections.evidence import build
        from pf.projections.report_audit import audit

        r = build(project_dir, ctx.group, ctx.project)
        score, findings = audit(project_dir)
        context.add_output_metadata({
            "metrics": r["metrics"], "pages": r["pages"], "score": score,
            "errors": sum(1 for f in findings if f.severity == "error"),
            "path": MetadataValue.path(str(reporting_dir(project_dir))),
        })

    return ToolContribution(assets=[_reporting])


# ------------------------------------------------------------------ loops --
def loops() -> dict[str, tuple[Any, Any]]:
    """The loop this tool owns. Returned as {name: (LoopSpec, body)}."""
    from pf.loops.runner import LoopRun, LoopSpec

    spec = LoopSpec(
        name="dashboard-coverage",
        description="Score the reporting layer; find metrics no page shows and pages "
                    "referencing metrics that do not exist.",
        autonomy="L1", cadence="daily", token_budget=0, writes=False,
    )

    def body(root: Path, group: str, project: str, run: LoopRun) -> list[str]:
        from pf.projections.report_audit import audit as audit_report

        pdir = root / "groups" / group / "projects" / project
        if not has_reporting(pdir):
            return []
        score, findings = audit_report(pdir)
        out = [str(f) for f in findings if f.severity in ("error", "warning")]
        if score < 90:
            out.insert(0, f"report score {score}/100 — run the dashboard-loop skill")
        return out

    return {spec.name: (spec, body)}


# -------------------------------------------------------------------- cli --
def register_commands(app: Any) -> None:
    """`pf tool evidence …` — the same three verbs `pf report` offers."""
    import typer
    from rich.console import Console

    console = Console()
    ev_app = typer.Typer(help="Evidence: the reporting layer.")

    def _pdir(group: str, project: str) -> Path:
        from pf.cli import pdir
        return pdir(group, project)

    @ev_app.command("build")
    def cmd_build(group: str, project: str) -> None:
        """Regenerate the Evidence project from the semantic layer."""
        from pf.projections.evidence import build
        r = build(_pdir(group, project), group, project)
        console.print(f"[green]✓[/] {r['path']} · {r['metrics']} metric(s) · {r['pages']} page(s)")

    @ev_app.command("audit")
    def cmd_audit(group: str, project: str) -> None:
        """Mechanical quality score for the reporting layer."""
        from pf.projections.report_audit import audit
        score, findings = audit(_pdir(group, project))
        for f in findings:
            console.print(f"  {f}")
        console.print(f"score {score}/100")
        raise typer.Exit(1 if any(f.severity == "error" for f in findings) else 0)

    @ev_app.command("doctor")
    def cmd_doctor() -> None:
        h = health()
        console.print(("[green]✓[/] " if h["ok"] else "[red]✗[/] ") + h["detail"])
        raise typer.Exit(0 if h["ok"] else 1)

    app.add_typer(ev_app, name="evidence")



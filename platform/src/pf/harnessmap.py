def _contributions(caps: dict[str, Any], tools: dict[str, Any]) -> list[tuple[str, tuple[str, ...], tuple[str, ...]]]:
    """Who adds which gate rules: (contributor, denies, impact-gates), sorted."""
    out = []
    for name in sorted(caps):
        gate = getattr(caps[name], "gate", {}) or {}
        denies = tuple(_list(gate.get("denylist")))
        impacts = tuple(_list(gate.get("impact_required")))
        if denies or impacts:
            label = f"tool `{name}`" if name in tools else f"capability `{name}`"
            out.append((label, denies, impacts))
    return out



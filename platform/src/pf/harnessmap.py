def _group_loops_cell(g: Group) -> str:
    changed = []
    for lp in g.loops:
        bits = [lp.overridden] if lp.overridden else []
        if lp.waivers:
            bits.append(_n(lp.waivers, "waiver"))
        if bits:
            changed.append(f"`{lp.name}` ({', '.join(bits)})")
    cell = ", ".join(changed) or "the registry as shipped"
    if g.disabled:
        cell += "; off: " + ", ".join(f"`{n}`" for n, _w in g.disabled)
    return cell



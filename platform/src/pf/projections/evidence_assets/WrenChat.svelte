	function apiBase() {
		try {
			const q = new URLSearchParams(window.location.search).get('wren');
			if (q) {
				localStorage.setItem('wren.api', q);
				return q.replace(/\/$/, '');
			}
			const saved = localStorage.getItem('wren.api');
			if (saved) return saved.replace(/\/$/, '');
		} catch (e) {
			/* storage unavailable: use the default */
		}
		const host = window.location.hostname || '127.0.0.1';
		return `http://${host === 'localhost' ? 'localhost' : '127.0.0.1'}:${port}`;
	}

	// Every call goes to this project's own routes; a service that does not
	// serve this project answers 404 rather than another project's data.
	const scoped = (path) => `${api}/api/p/${encodeURIComponent(group)}/${encodeURIComponent(project)}${path.replace(/^\/api/, '')}`;
	async function call(path, body) {
		const res = await fetch(scoped(path), body ? { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) } : {});
		const data = await res.json().catch(() => ({}));
		if (!res.ok) {
			const detail = data.detail;
			const err = new Error(typeof detail === 'string' ? detail : detail?.message || `${res.status} ${res.statusText}`);
			err.status = res.status;
			err.detail = detail;
			throw err;
		}
		return data;
	}

	let served = [];
	async function connect() {
		status = 'checking';
		try {
			health = await call('/api/health');
			if (!health.ready && !health.cubes && !health.models) {
				status = 'notready';
				return;
			}
			catalog = await call('/api/catalog');
			acronyms = new Set(catalog.cubes.flatMap((c) => c.measures.flatMap((m) => m.label.match(/\b[A-Z]{2,4}\b/g) ?? [])));
			status = 'online';
			await tick();
			layout();
			// A shared link (?ask=…) asks its question once, on arrival.
			const shared = new URLSearchParams(window.location.search).get('ask');
			if (shared && !turns.some((t) => t.question === shared)) ask(shared);
		} catch (e) {
			if (e.status === 404) {
				served = e.detail?.served ?? [];
				status = 'elsewhere';
			} else {
				status = 'offline';
			}
		}
	}

	function persist() {
		try {
			sessionStorage.setItem(STORE_KEY(), JSON.stringify(turns.filter((t) => !t.pending).slice(-20)));
		} catch (e) {
			/* a private window: the conversation just is not kept */
		}
	}

	async function scrollDown() {
		await tick();
		thread?.lastElementChild?.scrollIntoView({ behavior: 'smooth', block: 'start' });
	}

	function lastPlan() {
		for (let i = turns.length - 1; i >= 0; i--) if (turns[i].result?.ok && turns[i].result.plan?.kind === 'cube') return turns[i].result.plan;
		return null;
	}

	async function ask(question, via = null) {
		const q = (question ?? draft).trim();
		if (!q || busy) return;
		draft = '';
		busy = true;
		const turn = { id: Date.now(), question: q, pending: true, view: 'chart', measure: null, started: performance.now() };
		turns = [...turns, turn];
		scrollDown();
		try {
			const result = via ? await via() : await call('/api/ask', { question: q, previous: lastPlan(), planner });
			Object.assign(turn, { result, pending: false, ms: Math.round(performance.now() - turn.started) });
			turn.view = result.chart && result.chart !== 'none' && result.chart !== 'table' ? 'chart' : 'table';
			turn.measure = result.columns?.find((c) => c.kind === 'measure')?.name ?? null;
			live = result.ok ? `Answer ready: ${result.interpretation}` : `Could not answer: ${result.message}`;
		} catch (e) {
			Object.assign(turn, { pending: false, error: String(e.message || e) });
			if (/Failed to fetch|NetworkError/i.test(turn.error)) status = 'offline';
			live = `Error: ${turn.error}`;
		}
		turns = turns;
		busy = false;
		persist();
		scrollDown();
		composer?.focus();
	}

	function runBuilder() {
		const body = { ...b, measures: b.measures, filters: b.filters.filter((f) => f.dimension && f.values.length) };
		if (bCube?.timeDimensions?.length && (b.granularity || b.start)) body.time_dimension = bCube.timeDimensions[0].name;
		showBuilder = false;
		const dl = (d) => (bCube.dimensions.find((x) => x.name === d)?.label ?? humanize(d)).toLowerCase();
		ask(`${b.measures.map((m) => short(bCube.measures.find((x) => x.name === m)?.label ?? m)).join(', ')}${b.dimensions.length ? ' by ' + b.dimensions.map(dl).join(', ') : ''}`, () =>
			call('/api/cube', body)
		);
	}

	function refine(turn) {
		const p = turn.result.plan;
		b = {
			cube: p.cube,
			measures: [...p.measures],
			dimensions: [...p.dimensions],
			granularity: p.granularity || '',
			start: p.start || '',
			end: p.end || '',
			filters: p.filters.map((f) => ({ ...f, values: [...f.values] })),
			limit: p.limit || 200
		};
		showBuilder = true;
	}

	async function remember(turn) {
		try {
			await call('/api/remember', { question: turn.question, sql: turn.result.sql || turn.result.planned_sql });
			turn.saved = 'saved';
		} catch (e) {
			turn.saved = `not saved — ${e.message}`;
		}
		turns = turns;
		persist();
	}

	async function share(turn) {
		const url = new URL(window.location.href);
		url.searchParams.set('ask', turn.question);
		url.searchParams.delete('wren');
		await copy(url.toString(), turn, 'linked');
	}

	function csv(turn) {
		const cols = turn.result.columns;
		const esc = (v) => (/[",\n]/.test(String(v ?? '')) ? `"${String(v).replace(/"/g, '""')}"` : String(v ?? ''));
		const text = [cols.map((c) => esc(c.label)).join(','), ...turn.result.rows.map((r) => cols.map((c) => esc(r[c.name])).join(','))].join('\n');
		const a = document.createElement('a');
		a.href = URL.createObjectURL(new Blob([text], { type: 'text/csv' }));
		a.download = `${project}-answer-${turn.result.run_id || turn.id}.csv`;
		a.click();
		URL.revokeObjectURL(a.href);
	}

	async function copy(text, turn, flag = 'copied') {
		try {
			await navigator.clipboard.writeText(text);
			turn[flag] = true;
			turns = turns;
			setTimeout(() => ((turn[flag] = false), (turns = turns)), 1500);
		} catch (e) {
			/* clipboard blocked: the SQL is on screen to select */
		}
	}

	function sortBy(turn, col) {
		const dir = turn.sort?.col === col.name && turn.sort.dir === 'desc' ? 'asc' : 'desc';
		turn.sort = { col: col.name, dir };
		turn.result.rows = [...turn.result.rows].sort((a, z) => {
			const x = a[col.name];
			const y = z[col.name];
			if (x === y) return 0;
			if (x === null || x === undefined) return 1;
			if (y === null || y === undefined) return -1;
			return (x < y ? -1 : 1) * (dir === 'asc' ? 1 : -1);
		});
		turns = turns;
	}

	function followUps(turn) {
		const p = turn.result?.plan;
		if (!p || p.kind !== 'cube') return [];
		const out = [];
		if (!p.granularity) out.push('By month');
		if (p.granularity === 'month') out.push('By quarter instead');
		if (!p.start) out.push('Over the last 12 months');

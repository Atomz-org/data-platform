def _hooks(settings: dict[str, Any], root: Path, source: str) -> list[Hook]:
    out = []
    for event, entries in sorted((settings.get("hooks") or {}).items()):
        for entry in _list(entries):
            matcher = str(entry.get("matcher") or "*")
            for h in _list(entry.get("hooks")):
                cmd = str(h.get("command") or "")
                # The script, not its last argument: `notify.sh stop` is notify.sh.
                words = [Path(w).name for w in cmd.replace('"', "").split()]
                scripts = [w for w in words if w.endswith((".py", ".sh"))]
                script = scripts[-1] if scripts else (words[-1] if words else "")
                out.append(Hook(event, matcher, script, _EFFECTS.get(script, ""), source))
    return out



def _node(nid: str, label: str, cls: str, count: int | None = None,
          indent: str = "    ", present: bool | None = None) -> str:
    """One box. Grey and stated as absent when it is not there.

    Drawn rather than dropped: the shape of the map is then the same in every
    project, so a reader who knows one knows them all, and a hole is visible as
    a hole instead of as an absence they have to notice.

    `count` for a quantity, `present` for a fixed artefact — a two-file manifest
    labelled "2" answers a question nobody asked.
    """
    if count is not None:
        cls = cls if count else "neutral"
        label = f"{label}<br/>{count}" if count else f"{label}<br/>none yet"
    elif present is not None and not present:
        cls, label = "neutral", f"{label}<br/>none yet"
    return f'{indent}{nid}["{label}"]:::{cls}'


def _spine(a: Arch) -> list[str]:
    """Ingest to delivery, with this project's real counts on every stage."""
    src_dir = a.pdir / "src" / a.module / "sources"
    src_names = ", ".join(sorted(p.stem for p in src_dir.glob("[!_]*.py"))[:3])
    pages = len(list((a.pdir / "reporting" / "pages").rglob("*.md")))
    inner = "        "

    out = [
        "```mermaid", "flowchart LR",
        '    subgraph LI["ingest"]',
        f"{inner}direction TB",
        _node("I1", "dlt sources" + (f"<br/>{viz.esc(src_names, 34)}" if src_names else ""),
              "ingress", a.n("sources"), inner),
        _node("I2", f"pipeline<br/>{viz.esc(a.module, 24)}", "platform", indent=inner),
        _node("I3", "raw tables", "raw", a.n("raw_tables"), inner),
        "    end",
        '    subgraph LT["transform · dbt"]',
        f"{inner}direction TB",
        _node("T1", "staging", "model", a.n("staging"), inner),
        _node("T2", "marts", "model", a.n("marts"), inner),
        _node("T3", "data tests", "model", a.n("dbt_tests"), inner),
        "    end",
        '    subgraph LS["semantics"]',
        f"{inner}direction TB",
        _node("S1", "metrics", "metric", a.n("metrics"), inner),
        _node("S2", "dimensions", "metric", a.n("dimensions"), inner),
        _node("S3", "MDL contract", "platform", indent=inner,
              present=a.by_key("mdl").present),
        "    end",
        '    subgraph LD["delivery"]',
        f"{inner}direction TB",
        _node("D1", "exposures", "exposure", a.n("exposures"), inner),
        _node("D2", "Evidence pages", "exposure", pages, inner),
        "    end",
        "    I1 --> I2 --> I3 --> T1 --> T2",
        "    T2 --> S1 --> D1 --> D2",
        "    T2 --> S2",
        "    S1 -.published as.-> S3",
        "    T2 -.asserted by.-> T3",
    ]
    if a.is_rollup:
        # The one legitimate cross-entity read in the platform, and the only
        # reason a sister name appears anywhere in this document.
        out.append(_node("RU", "sisters attached READ_ONLY<br/>"
                               f"{viz.esc(', '.join(a.sisters) or 'none yet', 40)}",
                         "project"))
        out.append("    RU --> T1")
    out += viz.classdefs(["ingress", "platform", "raw", "model", "metric",
                          "exposure", "neutral", "project", "lane"])
    out += ["    class LI,LT,LS,LD lane", "```"]
    return out


def _example(a: Arch) -> list[str]:
    """The same spine, but with this project's own names on it.

    A generic diagram teaches the shape; only a real chain teaches that
    `stg_stripe__charges` is what `revenue` is actually built from. That is the
    fact an agent would otherwise reconstruct by reading four files.
    """
    if not a.chain.steps:
        return [f"_{a.chain.note}_"]

    cls = {"Source": "ingress", "Table": "raw", "Model": "model",
           "Metric": "metric", "Exposure": "exposure", "Dimension": "metric"}
    used = {cls.get(k, "neutral") for k, _ in a.chain.steps}
    out = ["```mermaid", "flowchart LR"]
    ids = []
    if a.chain.truncated:
        ids.append("XU")
        used.add("neutral")
        out.append(_node("XU", "… further upstream", "neutral"))
    for i, (kind, name) in enumerate(a.chain.steps):
        nid = f"X{i}"
        ids.append(nid)
        out.append(_node(nid, f"{viz.esc(kind, 14)}<br/>{viz.esc(name, 34)}",
                         cls.get(kind, "neutral")))
    out.append("    " + " --> ".join(ids))
    out += viz.classdefs(sorted(used))
    out.append("```")
    if a.chain.note:
        out.append("")
        out.append(f"_{a.chain.note}_")
    return out


def _control(a: Arch) -> list[str]:
    """What stops a bad change, and what each thing is reading when it does.

    Worth drawing separately from the spine because the enforcement path runs
    *across* it: one annotation file decides a staging model, a PII policy and a
    monitor, and no left-to-right pipeline shows that.
    """
    ci = a.by_key("ci")
    inner = "        "
    out = ["```mermaid", "flowchart TB",
           _node("A", "annotations<br/>contracts/annotations.yaml", "platform",
                 a.n("annotations")),
           _node("O", "ontology<br/>platform + group + project", "platform"),
           _node("P", "policy rules", "platform", a.n("policy")),
           # Deliberately not a node count. Columns are backfilled from
           # `information_schema`, so the total differs between a machine with a
           # warehouse and a CI runner without one — and a number that moves
           # with the environment turns `pf arch --check` into a coin toss. The
           # spine's counts all come from annotations and the dbt manifest,
           # which travel with the checkout.
           _node("K", "knowledge graph<br/>kg_search · impact_analysis",
                 "platform" if a.counts else "neutral"),
           '    subgraph LG["what it stops"]',
           f"{inner}direction TB",
           _node("E1", "pf check<br/>conformance", "good", indent=inner),
           _node("E2", "PreToolUse hook<br/>denies secrets + generated files",
                 "good" if a.by_key("settings").present else "neutral", indent=inner),
           _node("E3", "pre-commit<br/>blast radius", "good", indent=inner),
           _node("E4", f"CI<br/>{viz.esc(Path(ci.where).name if ci.where else 'none', 28)}",
                 "good" if ci.present else "neutral", indent=inner),
           "    end",
           "    A --> O --> P",
           "    A --> K",
           "    P -.governs.-> K",
           "    K --> E2",
           "    K --> E3",
           "    K --> E4",
           "    O --> E1",
           ]
    out += viz.classdefs(["platform", "good", "neutral", "lane"])
    out += ["    class LG lane", "```"]
    return out


_STATE = {"ok": "✓", "gap": "**gap**", "optional": "—"}


def _coverage(a: Arch) -> list[str]:
    """Every feature, present or not, grouped by lane.

    The absent rows are the ones that earn this table. A reader can see that a
    project has no exposures — and therefore that impact analysis stops at its
    marts — without discovering it by running an impact query that comes back
    empty and looking safe.
    """
    out = ["| feature | | where | what it is |", "|---|---|---|---|"]
    for lane in LANES:
        rows = [p for p in a.found if p.feature.lane == lane]
        if not rows:
            continue
        out.append(f"| **{lane}** | | | |")
        for p in rows:
            mark = _STATE[p.state]
            n = f" {p.count}" if p.present and p.countable and p.count > 1 else ""
            where = f"`{p.where}`" if p.where else ""
            why = p.feature.why if p.present else f"{p.feature.why} — `{p.feature.made_by}`"
            out.append(f"| {p.feature.title} | {mark}{n} | {where} | {why} |")
    return out


def render(a: Arch) -> str:
    """The map. Deterministic for a fixed project: no dates, everything sorted."""
    kind = "roll-up" if a.is_rollup else "entity"
    lines = [
        HEADER,
        f"# {a.project} — architecture",
        "",
        f"**{a.group}** group · {kind} · warehouse `{a.warehouse or 'unset'}` · "
        f"module `{a.module}`"
        + (f" · sisters attached: {', '.join(a.sisters) or 'none'}" if a.is_rollup else ""),
        "",
        ("Generated from this project alone. Sister projects are never read; "
         "cross-entity questions belong in the roll-up."),
        "",
        "## The spine",
        "",
    ]
    lines += _spine(a)
    lines += ["", "## A real path through it", ""]
    lines += _example(a)
    lines += ["", "## What enforces what", ""]
    lines += _control(a)
    lines += ["", "## Every feature, present or not", ""]
    lines += _coverage(a)

    # Named here rather than given rows: nine capabilities that each write one
    # documentation page would be nine near-identical lines in the table. One
    # that writes somewhere nothing else claims does earn a row — see
    # `pf.features.derive`.
    if a.caps:
        lines += ["", f"**Capabilities:** {', '.join(f'`{c}`' for c in a.caps)}"]
    if a.tools:
        lines += ["", f"**Tools enabled:** {', '.join(f'`{t}`' for t in a.tools)}"]
    if a.pii:
        lines += ["", (f"**PII columns:** {a.pii} — masked by policy, "
                       "never selected into a mart unaggregated")]

    gaps = a.gaps
    if gaps:
        lines += ["", "## Gaps", ""]
        lines += [f"- **{p.feature.title}** — {p.feature.why}. Fix: `{p.feature.made_by}`"
                  for p in gaps]

    if a.unmapped:
        lines += ["", "## Unmapped", "",
                  ("Present in the project and claimed by no feature in "
                   "`pf.architecture.FEATURES`. Either it belongs in the "
                   "registry or it does not belong in the project:"), ""]
        lines += [f"- `{u}`" for u in a.unmapped]

    lines += ["", "---", "",
              ("Query before reading: `kg_search`, `kg_neighbors`, `kg_path`, "
               "`impact_analysis`. Regenerate this file with "
               f"`pf arch {a.group} {a.project}`.")]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ write ----
def write(root: str | Path, group: str, project: str) -> tuple[Path, Arch]:
    a = gather(root, group, project)
    out = a.pdir / DOC_REL
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(a))
    return out, a


@dataclass
class Drift:
    """Is the committed map still what the project would produce?"""

    project: str
    missing: bool = False
    stale: bool = False
    unmapped: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not (self.missing or self.stale or self.unmapped)

    def __str__(self) -> str:
        if self.missing:
            return f"{self.project}: no architecture map — run `pf arch`"
        bits = []
        if self.stale:
            bits.append("map is stale — the project changed since it was written")
        if self.unmapped:
            bits.append(f"{len(self.unmapped)} unmapped entry(ies): "
                        + ", ".join(self.unmapped))
        if not bits:
            return f"{self.project}: ok"
        return f"{self.project}: " + "; ".join(bits)


def drift(root: str | Path, group: str, project: str) -> Drift:
    a = gather(root, group, project)
    out = a.pdir / DOC_REL
    d = Drift(project=f"{group}/{project}", unmapped=list(a.unmapped))
    if not out.exists():
        d.missing = True
        return d
    d.stale = out.read_text() != render(a)
    return d


def lint_doc(text: str) -> list[str]:
    """Every mermaid block in a rendered map, checked. Empty means clean."""
    problems: list[str] = []
    for i, b in enumerate(viz.blocks(text), 1):
        problems += [f"diagram {i}: {p}" for p in viz.lint(b)]
    return problems


def summary(a: Arch) -> dict[str, object]:
    """Machine-readable, for the UI and for `pf pr report`."""
    return {
        "group": a.group, "project": a.project, "rollup": a.is_rollup,
        "warehouse": a.warehouse,
        "capabilities": a.caps, "tools": a.tools,
        "features": {p.feature.key: {"state": p.state, "count": p.count,
                                     "source": p.feature.source}
                     for p in a.found},
        "gaps": [p.feature.key for p in a.gaps],
        "unmapped": a.unmapped,
        "nodes": sum(a.counts.values()),
    }


def as_json(a: Arch) -> str:
    return json.dumps(summary(a), indent=2, sort_keys=True)

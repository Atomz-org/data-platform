def _loops(root: Path, group: str, tools: dict[str, Any]) -> tuple[list[Loop], list[tuple[str, str]]]:
    try:
        from pf.loops import config
        from pf.loops.registry import SPECS
    except Exception:  # noqa: BLE001
        return [], []

    owner: dict[str, str] = {}
    for name in sorted(tools):
        try:
            hook = tools[name].hook("loops")
            if hook is not None:
                owner.update(dict.fromkeys(hook(), f"tool `{name}`"))
        except Exception:  # noqa: BLE001 — a broken loop hook is that tool's problem
            continue

    try:
        specs = config.resolve(root, group)
        overrides = config.overrides(root, group)
        disabled = config.disabled(root, group)
    except Exception:  # noqa: BLE001 — a malformed loops.yaml is reported by `pf loop list`
        specs, overrides, disabled = dict(SPECS.items()), {}, {}

    rows = []
    for name in sorted(specs):
        s = specs[name]
        o = overrides.get(name)
        changed = []
        if o is not None:
            for f in ("cadence", "token_budget", "autonomy"):
                if getattr(o, f, None) not in (None, ""):
                    changed.append(f.replace("_", " "))
        source = "registry" if name in SPECS else owner.get(name, "registry")
        rows.append(
            Loop(
                name,
                str(s.cadence),
                str(s.autonomy),
                int(s.token_budget or 0),
                bool(s.writes),
                str(s.description),
                len(getattr(o, "waivers", ()) or ()) if o else 0,
                source,
                ", ".join(changed),
            )
        )
    return rows, sorted(disabled.items())


def _workflow(root: Path, project: str, caps: dict[str, Any], tools: dict[str, Any]) -> tuple[str, list[Job]]:
    rel = f".github/workflows/{project}.yml"
    doc = _yaml(root / rel)
    jobs = doc.get("jobs") if isinstance(doc.get("jobs"), dict) else {}
    if not jobs:
        return "", []
    by_job = {}
    for name in sorted(caps):
        for job in getattr(caps[name], "ci_jobs", {}) or {}:
            by_job.setdefault(job, f"tool `{name}`" if name in tools else f"capability `{name}`")
    out = []
    for job in jobs:
        spec = jobs[job] if isinstance(jobs[job], dict) else {}
        cond = str(spec.get("if") or "")
        outputs = list(dict.fromkeys(re.findall(r"outputs\.(\w+)", cond)))
        if not cond:
            when = "always"
        elif outputs == ["any"]:
            when = "any change in the project"
        else:
            when = " or ".join(outputs) + " changed"
        if job == "changes":
            source, when = "the path filter", "always"
        else:
            source = by_job.get(job, "the workflow")
        out.append(Job(str(job), source, when))
    return rel, out


def _repo_workflows(root: Path, projects: set[str]) -> tuple[list[Workflow], list[str]]:
    """Workflows every pull request runs, and those a path filter narrows."""
    every, filtered = [], []
    wdir = root / ".github" / "workflows"
    if not wdir.is_dir():
        return every, filtered
    for f in sorted(wdir.glob("*.yml")):
        if f.stem in projects or f.stem == "agent-context":
            continue
        doc = _yaml(f)
        on = doc.get("on", doc.get(True))
        if not isinstance(on, dict) or "pull_request" not in on:
            continue
        pr = on.get("pull_request") or {}
        if isinstance(pr, dict) and pr.get("paths"):
            filtered.append(f.stem)
            continue
        when = "every pull request" + (" · daily" if "schedule" in on else "")
        jobs = tuple(str(j) for j in (doc.get("jobs") or {}))
        every.append(Workflow(f.stem, jobs, when))
    return every, filtered



	// Any ISO 4217 code a metric declares (`inr`, `usd0k`, `chf`): the symbol comes
	// from the browser's own currency data, so no project's currency is special.
	const symbolCache = {};
	function currencyOf(code) {
		const iso = /^[a-z]{3}/.test(code) ? code.slice(0, 3).toUpperCase() : '';
		if (!iso || iso === 'NUM' || iso === 'PCT') return null;
		if (!(iso in symbolCache)) {
			try {
				const part = new Intl.NumberFormat('en-US', { style: 'currency', currency: iso, currencyDisplay: 'narrowSymbol' }).formatToParts(1).find((p) => p.type === 'currency');
				symbolCache[iso] = part ? (part.value.length > 1 && /^[A-Z]+$/.test(part.value) ? `${part.value} ` : part.value) : null;
			} catch (e) {
				symbolCache[iso] = null;
			}
		}
		return symbolCache[iso];
	}

	function compact(v, symbol = '', digits = 1) {
		const a = Math.abs(v);
		for (const [n, s] of SCALES) if (a >= n) return `${v < 0 ? '−' : ''}${symbol}${(a / n).toFixed(a / n >= 100 ? 0 : digits)}${s}`;
		return `${v < 0 ? '−' : ''}${symbol}${a.toLocaleString('en-US', { maximumFractionDigits: 2 })}`;
	}

	function fmt(v, format = '', short = false) {
		if (v === null || v === undefined || v === '') return '—';
		const n = typeof v === 'number' ? v : Number(v);
		if (!Number.isFinite(n)) return String(v);
		const code = String(format || '').toLowerCase();
		const pct = code.match(/^pct(\d)?/);
		if (pct) return `${(n * 100).toLocaleString('en-US', { minimumFractionDigits: +(pct[1] ?? 1), maximumFractionDigits: +(pct[1] ?? 1) })}%`;
		const sym = currencyOf(code);
		if (sym) return Math.abs(n) >= 1e4 || short ? compact(n, sym) : `${sym}${n.toLocaleString('en-US', { maximumFractionDigits: 2 })}`;
		const num = code.match(/^num(\d)/);
		const digits = num ? +num[1] : Math.abs(n) >= 100 ? 0 : 2;
		if (short && Math.abs(n) >= 1e4) return compact(n);
		return n.toLocaleString('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits });
	}

	const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
	function fmtTime(v, grain = 'day') {
		const d = new Date(String(v).replace(' ', 'T'));
		if (Number.isNaN(d.getTime())) return String(v);
		const y = d.getFullYear();
		if (grain === 'year') return `${y}`;
		if (grain === 'quarter') return `Q${Math.floor(d.getMonth() / 3) + 1} ${y}`;
		if (grain === 'month') return `${MONTHS[d.getMonth()]} ${y}`;
		if (grain === 'week') return `Wk ${d.getDate()} ${MONTHS[d.getMonth()]} ${String(y).slice(2)}`;
		return `${d.getDate()} ${MONTHS[d.getMonth()]} ${y}`;
	}

	const sentence = (t) => `${t.charAt(0).toUpperCase()}${t.slice(1)}${/[.!?]$/.test(t) ? '' : '.'}`;

	function humanize(v) {
		if (v === null || v === undefined) return '—';
		const s = String(v);
		if (s === 'true') return 'Yes';
		if (s === 'false') return 'No';
		if (/^[A-Z0-9_]+$/.test(s)) return s; // codes stay as written (GOLDM)
		const t = s.replace(/_/g, ' ');
		return t.charAt(0).toUpperCase() + t.slice(1);
	}


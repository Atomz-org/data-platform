def _tool_rows(root: Path, group: str, project: str, tools: dict[str, Any]) -> list[ToolRow]:
    try:
        from pf.tools import resolve

        cfg = resolve(root, group, project) if project else resolve(root, group, "")
    except Exception:  # noqa: BLE001
        return []
    rows = []
    for name in sorted(cfg):
        c = cfg[name]
        if not c.enabled or name not in tools:
            continue
        t = tools[name]
        cap = t.capability
        gate = (getattr(cap, "gate", {}) or {}) if cap else {}
        loops: tuple[str, ...] = ()
        try:
            hook = t.hook("loops")
            loops = tuple(sorted(hook())) if hook is not None else ()
        except Exception:  # noqa: BLE001
            loops = ()
        surface = f"port {t.surface.port}{t.surface.path}" if t.surface else ""
        rows.append(
            ToolRow(
                name,
                t.title,
                t.summary,
                c.source,
                surface,
                tuple(_list(gate.get("denylist"))),
                tuple(_list(gate.get("impact_required"))),
                tuple(sorted(getattr(cap, "ci_jobs", {}) or {})) if cap else (),
                bool(t.dagster),
                loops,
                tuple(getattr(t.dbt, "artefacts", ()) or ()) if t.dbt else (),
                tuple(sorted((getattr(cap, "settings", {}) or {}).get("enabledPlugins") or {})) if cap else (),
            )
        )
    return rows


def _present_caps(root: Path, pdir: Path, group: str, project: str, caps: dict[str, Any]) -> list[str]:
    """Capabilities this project has, judged by their own files, as the architecture map does."""
    try:
        from pf.capabilities import render
    except Exception:  # noqa: BLE001
        return []
    ctx = {"group": group, "project": project, "module": project.replace("-", "_")}
    out = []
    for name in sorted(caps):
        files = getattr(caps[name], "files", {}) or {}
        if not files:
            continue
        targets = [(root if rel.startswith(".github/") else pdir) / render(rel, ctx) for rel in files]
        if all(t.is_file() for t in targets):
            out.append(name)
    return out


def _policies(caps: dict[str, Any], present: list[str]) -> list[str]:
    out = []
    for name in present:
        for p in getattr(caps.get(name), "policies", ()) or ():
            pid = p.get("id") or p.get("name")
            if pid:
                out.append(str(pid))
    return sorted(set(out))


def _targets(pdir: Path) -> list[tuple[str, str]]:
    doc = _yaml(pdir / "transform" / "profiles.yml")
    for value in doc.values():
        if isinstance(value, dict) and isinstance(value.get("outputs"), dict):
            return [
                (str(n), str(spec.get("type") or "")) for n, spec in value["outputs"].items() if isinstance(spec, dict)
            ]
    return []


def _air(path: Path) -> tuple[int, int]:
    doc = _yaml(path)
    return len(_list(doc.get("baseline"))), len(_list(doc.get("accepted")))


def _notify(gdir: Path) -> list[tuple[str, str]]:
    doc = _yaml(gdir / "notify.yaml")
    ch = doc.get("channels") if isinstance(doc.get("channels"), dict) else {}
    return sorted((str(k), str(v)) for k, v in ch.items())


def _manifest(root: Path, group: str) -> Any:
    try:
        from pf import groups as manifests

        if manifests.exists(root, group):
            return manifests.load(root, group)
    except Exception:  # noqa: BLE001 — a malformed manifest is `pf group verify`'s to report
        return None
    return None


def _projects_in(gdir: Path) -> list[str]:
    pdir = gdir / "projects"
    if not pdir.is_dir():
        return []
    return sorted(p.name for p in pdir.iterdir() if p.is_dir() and not p.name.startswith("."))


def _by_harness(p: Project, power_tools: bool) -> list[tuple[str, str, str, str]]:
    """The scorecard's rows, as they hold in this project.

    `pf.harness.HARNESSES` says what each tool gets repository-wide. Two of
    its cells are decided per project: Claude Code's pre-tool gate exists only
    where this project's settings declare the hook, and its graph is the root
    `.mcp.json` plus whatever this project's own `.mcp.json` adds — servers the
    other harnesses' configs, rendered from the root file, never see.
    """
    try:
        from pf.harness import HARNESSES
    except Exception:  # noqa: BLE001 — the scorecard is optional to the map
        return []
    gated = any(h.event == "PreToolUse" and h.script == "pre_tool_use.py" for h in p.hooks)
    rows = []
    for h in HARNESSES:
        if h.name == "Claude Code":
            graph = (
                "`.mcp.json` + power-tools plugin" if power_tools else "`.mcp.json`; no plugin, so no `pf` server"
            ) + (" + this project's " + ", ".join(f"`{s}`" for s in p.local_servers) if p.local_servers else "")
            gate = (
                "hook — `pre_tool_use.py` on every Edit/Write"
                if gated
                else "**none — this project's settings declare no hook**"
            )
            rows.append((h.name, "`CLAUDE.md` + this project's hooks", graph, gate))
        else:
            rows.append((h.name, h.entry, h.graph, h.pre_tool_gate))
    return rows



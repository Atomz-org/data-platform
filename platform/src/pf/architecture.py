"""Design one project's architecture map, from the project itself.

Every project in this repository has the same shape and different contents: a
dlt ingest, a dbt transform, a semantic layer, a governance overlay, a delivery
surface and an operational wiring. An agent arriving at one of them currently
learns that shape by reading it — twenty-odd directories, a dbt project, a
settings file — which costs thousands of tokens to rediscover something the
platform already knows.

This module writes it down instead, per project, as `kg/architecture.md`. It is
a **projection**, never hand-maintained: `pf bootstrap` regenerates it, so a new
project gets one at scaffold time and an existing one gets it on the next
bootstrap, with no per-project work either way.

## Why a feature registry rather than a template

The obvious implementation is a template with the sections someone thought of on
the day. That is exactly how a project feature goes missing: `catalog/` and
`evals/` were both added to the scaffolder long after the first documentation of
it was written, and neither appeared in any overview until somebody noticed.

So the shape of the document is a **registry** and the document is generated
from it. Two consequences make the omission failure structural rather than a
matter of diligence:

  every feature is reported     including the absent ones, which are the ones a
                                  template silently omits and the ones a reader
                                  most needs to see
  everything else is flagged    `unmapped` lists any top-level entry in the
                                  project that no feature claims, so a directory
                                  added by a future capability shows up as a hole
                                  in the map rather than not showing up at all

`pf arch --check` fails on both a stale document and a non-empty `unmapped`, so
the second one is a build error rather than a note nobody reads.

## Why the registry is composed, not listed

`CORE` below is what the *platform* puts in every project. It is not the whole
registry, and `features()` is: it adds whatever the installed capabilities and
tools declare or imply, resolved at call time.

That indirection is the difference between a map that survives a new tool and
one that breaks on it. A tool arrives by installing a package that advertises a
`pf.tools` entry point, and nothing here is supposed to change when one does —
so a tool writing `elementary/` into a project must claim that directory itself.
With a closed list it could not: every project would report an unmapped
directory and fail `pf arch --check`, fixable only by patching platform code.

Contribution costs nothing in the common case. `pf.features.derive` reads what a
capability or tool *already declares* — its `files`, its `dbt.artefacts` — and
adds a row only for territory nothing else claims. `Capability.feature` and
`Tool.features` are there when a derivation would produce a poor title or miss a
`count_kind`.

## Scope

**One project. Never a sister.** Nothing here reads outside the project
directory except the repository-level artefacts that are *about* this project —
its CI workflow and its Dagster code location — and, for a roll-up, the sister
*names* the group already publishes in its group card. Business logic does not
transfer between entities, and neither does an architecture read from the wrong
one.

## Why there is no date in the output

The context card carries a generation date and is rewritten every day because of
it. This document is regenerated by every `pf bootstrap --all`, on eight
projects, and a date would make each of those runs an eight-file diff that says
nothing. Without one, the file changes when the project changes — which is what
makes `pf arch --check` worth wiring into CI.
"""


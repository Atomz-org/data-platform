# ------------------------------------------------------------- composition ---
def _installed_capabilities() -> list:
    """Every registered capability, tools' ones included.

    `CAPABILITIES` is a mutable global that tool registration adds to by side
    effect, so what it holds depends on whether discovery has run. The CLI
    triggers it at import and a bare `import pf.architecture` does not, which is
    how the same project produced two different maps depending on who asked.
    """
    try:
        from pf.capabilities import CAPABILITIES
        from pf.tools import register_capabilities

        register_capabilities()
        return sorted(CAPABILITIES.values(), key=lambda c: c.name)
    except Exception:  # noqa: BLE001 — a broken registry must not stop the map
        return []


def _installed_tools() -> list:
    try:
        from pf.tools import all_tools

        return sorted(all_tools().values(), key=lambda t: t.name)
    except Exception:  # noqa: BLE001
        return []


def features() -> tuple[Feature, ...]:
    """The registry: platform features, plus what the installed extras bring.

    Order is reading order — `CORE` as declared, then contributions by name —
    and it is stable for a fixed installation, which is what lets the rendered
    map be byte-compared for drift.

    A key already present wins. That makes `CORE` authoritative over a
    derivation, and an explicitly declared `Capability.feature` authoritative
    over the derivation for the same capability.
    """
    out: dict[str, Feature] = {f.key: f for f in CORE}
    claimed: set[str] = {s for f in CORE for s in f.segments}

    def add(f: Feature | None) -> None:
        if f is None or f.key in out:
            return
        out[f.key] = f
        claimed.update(f.segments)

    for cap in _installed_capabilities():
        add(getattr(cap, "feature", None))
        add(derive(cap.name, cap.description, tuple(cap.files),
                   source=f"capability:{cap.name}",
                   made_by=f"pf capability-add {cap.name}",
                   optional=not cap.default_enabled, claimed=claimed))

    for tool in _installed_tools():
        for f in getattr(tool, "features", ()):
            add(f)
        paths = tuple(getattr(tool.capability, "files", {}) or {})
        paths += tuple(getattr(tool.dbt, "artefacts", ()) or ())
        add(derive(tool.name, tool.summary, paths, source=f"tool:{tool.name}",
                   made_by=f"pf tool enable {tool.name}",
                   optional=not tool.default_enabled, claimed=claimed))

    return tuple(out.values())


@dataclass
class Presence:
    """One feature, as found in one project."""

    feature: Feature
    count: int = 0
    #: Only ever the first matching path, for the reader to open. Not a list:
    #: forty staging models are a count, not thirty-nine lines of noise.
    where: str = ""

    @property
    def present(self) -> bool:
        return self.count > 0

    @property
    def countable(self) -> bool:
        """Is `count` a quantity, or just how many of a fixed file set exist?

        `mdl/` holds exactly two files and always will; printing "2" beside it
        says nothing. `transform/models/marts/**/*.sql` holding 996 is the
        single most useful number on the page. The difference is whether the
        globs name specific files or a set, so that is what is asked.
        """
        f = self.feature
        return bool(f.count_kind) or all("*" in g for g in f.paths + f.repo_paths)

    @property
    def state(self) -> str:
        if self.present:
            return "ok"
        return "optional" if self.feature.optional else "gap"


@dataclass
class Chain:
    """A real path through the project, as (kind, name) upstream to downstream."""

    steps: list[tuple[str, str]] = field(default_factory=list)
    note: str = ""
    #: The walk hit its hop limit with lineage still above it. Said out loud in
    #: the diagram, because a chain that starts at a mart otherwise reads as a
    #: project whose marts have no sources.
    truncated: bool = False


@dataclass
class Arch:
    group: str
    project: str
    pdir: Path
    root: Path
    is_rollup: bool = False
    sisters: list[str] = field(default_factory=list)
    warehouse: str = ""
    module: str = ""
    counts: dict[str, int] = field(default_factory=dict)
    found: list[Presence] = field(default_factory=list)
    unmapped: list[str] = field(default_factory=list)
    tools: list[str] = field(default_factory=list)
    caps: list[str] = field(default_factory=list)
    pii: int = 0
    chain: Chain = field(default_factory=Chain)

    def by_key(self, key: str) -> Presence:
        """A feature by key, or an empty stand-in.

        Never raises. The registry is composed from what is installed, so a
        renderer that names a key cannot assume it exists — and a spine that
        crashes because someone removed a capability is worse than one that
        draws the stage as empty, which is what it is.
        """
        for p in self.found:
            if p.feature.key == key:
                return p
        return Presence(Feature(key, key, "operate", "not registered",
                                (f"{key}/**",), made_by="—"), 0)

    def n(self, key: str) -> int:
        return self.by_key(key).count

    @property
    def gaps(self) -> list[Presence]:
        return [p for p in self.found if p.state == "gap"]



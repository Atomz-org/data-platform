def _project_gaps(p: Project, power_tools: bool) -> list[str]:
    """What this harness does not do, derived from what it declares."""
    gaps = []
    if not any(h.event == "PreToolUse" and h.script == "pre_tool_use.py" for h in p.hooks):
        gaps.append(
            "**No edit gate.** `.claude/settings.json` declares no PreToolUse hook running "
            "`platform/hooks/pre_tool_use.py`: nothing denies a write to a secret or a generated "
            "file before it lands, and no INTENT or DECISION is recorded. `pf bootstrap` restores it."
        )
    if not any(h.event == "PostToolUse" and h.script == "post_tool_use.py" for h in p.hooks):
        gaps.append(
            "**EXECUTION (stage 03) is not declared here.** Neither this project's "
            "`.claude/settings.json` nor the plugin runs `platform/hooks/post_tool_use.py` after a "
            "tool call, so an action INTENT opens is closed only when the gate blocks it, and "
            "`pf provenance verify` reports the rest as dangling. The repository root's settings do "
            "declare that hook; a session opened here with `pf work` reads this file, not that one."
        )
    if not power_tools:
        gaps.append(
            "**No `power-tools` plugin.** Without it there is no `pf` MCP server — `kg_search`, "
            "`impact_analysis` and the rest do not exist in this session — and no session-start, "
            "format or notify hook."
        )
    if not any("projects/**" in d or "../" in d for d in p.deny):
        gaps.append(
            "**Sisters are readable.** `permissions.deny` names no sister or other group; the "
            "isolation `AGENTS.md` §1 describes is discipline only here."
        )
    if not p.graph:
        gaps.append(
            "**No knowledge graph is tracked** (`kg/graph.json`). The impact gate is inert on every "
            "machine that has not run `pf kg build`, and the SessionStart hook says so on turn one."
        )
    if not p.workflow:
        gaps.append(
            f"**No CI workflow.** `.github/workflows/{p.project}.yml` does not exist; nothing judges "
            "a pull request against this project. `pf bootstrap` composes one from the capabilities."
        )
    paper = [
        v.path.split("/projects/", 1)[-1].split("/", 1)[-1]
        for v in p.verdicts
        if v.verdict == "allow" and v.rule.startswith("allowlist:") and _impact_on_paper(v.path, p)
    ]
    if paper:
        gaps.append(
            "**Impact-gated on paper, allowed in practice:** "
            + ", ".join(f"`{x}`" for x in paper)
            + ". `autoMergeAllowlist` is matched before `impact_required`, so the hook allows the edit "
            "and prints no blast radius, and the commit gate runs no impact analysis on it. Only CI's "
            "`impact-gate` job judges the change, and only for models and sources."
        )
    carried = [
        v.path.split("/projects/", 1)[-1].split("/", 1)[-1] if "/projects/" in v.path else v.path
        for v in p.verdicts
        if v.rule == "denylist_except"
    ]
    if carried:
        gaps.append(
            "**Generated, and hand-editable:** "
            + ", ".join(f"`{x}`" for x in carried)
            + ". `denylist_except` is matched before `denylist`, so the hook allows the edit; only the "
            "drift check in CI (`architecture`, `pf harness check`) catches a hand edit, after the fact."
        )
    if not p.evals:
        gaps.append(
            "**No eval case of this project's own.** `evals/cases/` holds nothing hand-written, so "
            "nothing checks that an agent still answers this entity's questions correctly. "
            "`pf evals-gen` grounds the toolkit templates; the cases that matter are written by hand."
        )
    if p.reporting and not any(f"{a}@{b}" == "evidence-bi@platform" for a, b in p.plugins):
        gaps.append(
            "**`reporting/` exists but the `evidence-bi` plugin is off**, so the reporting rules and "
            "the dashboard skills are not loaded in this session."
        )
    return gaps


def _impact_on_paper(rel: str, p: Project) -> bool:
    """Would `impact_required` have matched this path, had the allowlist not won?"""
    policy = _policy(p.root)
    try:
        from pf.loops.gate import _match

        return _match(rel, _list(policy.get("impact_required"))) is not None
    except Exception:  # noqa: BLE001
        return False



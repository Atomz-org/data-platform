	function niceTicks(min, max, count = 4) {
		if (min === max) {
			const pad = Math.abs(min) || 1;
			min -= pad;
			max += pad;
		}
		const span = max - min;
		const step0 = span / count;
		const mag = Math.pow(10, Math.floor(Math.log10(step0)));
		const step = [1, 2, 2.5, 5, 10].map((m) => m * mag).find((s) => span / s <= count) ?? 10 * mag;
		const lo = Math.floor(min / step) * step;
		const hi = Math.ceil(max / step) * step;
		const ticks = [];
		for (let v = lo; v <= hi + step / 2; v += step) ticks.push(+v.toPrecision(12));
		return ticks;
	}

	function lineModel(result, measureName, width, isDark = dark) {
		const tcol = result.columns.find((c) => c.kind === 'time');
		const dcol = result.columns.find((c) => c.kind === 'dimension');
		const mcol = result.columns.find((c) => c.name === measureName);
		const xs = [...new Set(result.rows.map((r) => String(r[tcol.name])))].sort();
		const keys = dcol ? [...new Set(result.rows.map((r) => String(r[dcol.name])))] : [mcol.label];
		const series = keys.map((k, i) => ({
			key: k,
			label: dcol ? humanize(k) : mcol.label,
			color: palette(i, isDark),
			points: xs.map((x) => {
				const row = result.rows.find((r) => String(r[tcol.name]) === x && (!dcol || String(r[dcol.name]) === k));
				const v = row ? Number(row[mcol.name]) : null;
				return Number.isFinite(v) ? v : null;
			})
		}));
		const vals = series.flatMap((s) => s.points).filter((v) => v !== null);
		const ticks = niceTicks(Math.min(0, ...vals), Math.max(...vals));
		const direct = series.length > 1 && series.length <= 4 && width >= 560;
		const m = { t: 12, r: direct ? 96 : 16, b: 28, l: width < 480 ? 52 : 64 };
		const h = 260;
		const iw = Math.max(80, width - m.l - m.r);
		const ih = h - m.t - m.b;
		const x = (i) => m.l + (xs.length === 1 ? iw / 2 : (i / (xs.length - 1)) * iw);
		const y = (v) => m.t + ih - ((v - ticks[0]) / (ticks[ticks.length - 1] - ticks[0])) * ih;
		const path = (pts) => {
			let d = '';
			let pen = false;
			pts.forEach((v, i) => {
				if (v === null) return (pen = false);
				d += `${pen ? 'L' : 'M'}${x(i).toFixed(1)},${y(v).toFixed(1)}`;
				pen = true;
			});
			return d;
		};
		const every = Math.max(1, Math.ceil(xs.length / Math.max(2, Math.floor(iw / 90))));
		// Direct labels at each line's end, nudged apart so two close series stay readable.
		const labels = [];
		if (direct) {
			for (const s of series) {
				const last = s.points.map((v, i) => (v === null ? -1 : i)).reduce((a, b) => Math.max(a, b), -1);
				if (last >= 0) labels.push({ label: s.label, color: s.color, x: x(last) + 8, y: y(s.points[last]) + 4 });
			}
			labels.sort((a, b) => a.y - b.y);
			for (let i = 1; i < labels.length; i++) if (labels[i].y - labels[i - 1].y < 14) labels[i].y = labels[i - 1].y + 14;
		}
		return { xs, series, ticks, m, h, iw, ih, x, y, path, every, tcol, mcol, labels };
	}

	function barModel(result, measureName, width, isDark = dark) {
		const dcol = result.columns.find((c) => c.kind === 'dimension');
		const mcol = result.columns.find((c) => c.name === measureName);
		// A breakdown reads largest first; a ranking already arrives in its order.
		const rows = result.rows.map((r) => ({ label: humanize(r[dcol.name]), v: Number(r[mcol.name]) }));
		if (!result.plan?.order_by) rows.sort((a, z) => (Number.isFinite(z.v) ? z.v : -Infinity) - (Number.isFinite(a.v) ? a.v : -Infinity));
		const vals = rows.map((r) => r.v).filter(Number.isFinite);
		const lo = Math.min(0, ...vals);
		const hi = Math.max(0, ...vals);
		const labelW = Math.min(180, Math.max(72, Math.max(...rows.map((r) => r.label.length)) * 7.2));
		const valueW = 76;
		const iw = Math.max(60, width - labelW - valueW - 8);
		const bh = 22;
		const gap = 8;
		const sx = (v) => ((v - lo) / (hi - lo || 1)) * iw;
		return { rows, lo, hi, labelW, valueW, iw, bh, gap, sx, h: rows.length * (bh + gap), mcol, zero: sx(0), pos: palette(0, isDark), neg: palette(1, isDark) };
	}

